import test from 'node:test';
import assert from 'node:assert/strict';
import {
  splitRequirementPrompt,
  sanitizeBlindedItem,
  getQuestionStatusForItem,
  isItemFullyAnswered,
  formatDisplayCodeLines,
  tokenizeVerilogLine,
} from './reviewLogic';
import { RubricQuestion } from '../types';

const TEST_RUBRIC: RubricQuestion[] = [
  { id: 'q1', code: 'Q1', prompt: 'Relevant?', options: ['yes', 'no', 'na'], autoRule: 'na_if_no_question' },
  { id: 'q2', code: 'Q2', prompt: 'Ambiguity?', options: ['yes', 'no', 'na'], autoRule: 'na_if_no_question' },
  { id: 'q3', code: 'Q3', prompt: 'Faithful?', options: ['yes', 'no', 'na'], autoRule: 'na_if_no_question' },
  { id: 'q4', code: 'Q4', prompt: 'Follows oracle?', options: ['yes', 'no', 'partly', 'na'], autoRule: 'na_if_no_oracle' },
  { id: 'q5', code: 'Q5', prompt: 'Unrelated assumptions?', options: ['yes', 'no'], autoRule: 'none' },
  { id: 'q6', code: 'Q6', prompt: 'Main failure cause?', options: ['ambiguity', 'implementation', 'none'], autoRule: 'none' },
];

test('splitRequirementPrompt isolates requirement and MODULE PORTS section', () => {
  const raw =
    'REQUIREMENT\nDesign an alarm latch with one-bit inputs clk, rst, err, tmo, armed.\nMODULE PORTS\ninput wire clk, output reg alarm';
  const res = splitRequirementPrompt(raw);
  assert.equal(res.requirement, 'Design an alarm latch with one-bit inputs clk, rst, err, tmo, armed.');
  assert.equal(res.ports, 'MODULE PORTS\ninput wire clk, output reg alarm');
});

test('sanitizeBlindedItem strips formal_outcome, evidence_logs, and model watermarks', () => {
  const raw = {
    review_id: 'R047',
    requirement_prompt: 'Design an alarm latch.',
    model_question: [],
    oracle_answer: '',
    generated_response: '// Author: generated by Claude\nmodule alarm_latch(); endmodule',
    formal_outcome: 'FAIL_ASSERTION',
    evidence_logs: 'cex trace at cycle 4',
  };
  const sanitized = sanitizeBlindedItem(raw, 'R001');
  assert.equal(sanitized.id, 'R047');
  assert.equal(sanitized.model_question.length, 0);
  assert.equal(sanitized.oracle_answer, '');
  assert.ok(!sanitized.generated_response.includes('Claude'));
  assert.equal('formal_outcome' in sanitized, false);
  assert.equal('evidence_logs' in sanitized, false);
});

test('getQuestionStatusForItem and isItemFullyAnswered handle auto-na rules accurately', () => {
  const itemNoQ = sanitizeBlindedItem(
    {
      review_id: 'R047',
      requirement_prompt: 'Design an alarm latch.',
      model_question: [],
      oracle_answer: '',
      generated_response: 'module m(); endmodule',
    },
    'R047'
  );

  assert.equal(getQuestionStatusForItem(itemNoQ, TEST_RUBRIC[0]).isAutoNa, true);
  assert.equal(getQuestionStatusForItem(itemNoQ, TEST_RUBRIC[3]).isAutoNa, true);
  assert.equal(getQuestionStatusForItem(itemNoQ, TEST_RUBRIC[4]).isAutoNa, false);

  // Only Q5 and Q6 are required when model_question and oracle_answer are empty
  assert.equal(isItemFullyAnswered(itemNoQ, { q5: 'no' }, TEST_RUBRIC), false);
  assert.equal(isItemFullyAnswered(itemNoQ, { q5: 'no', q6: 'none' }, TEST_RUBRIC), true);
});

test('tokenizeVerilogLine identifies keywords, literals, and comments', () => {
  const tokens = tokenizeVerilogLine("        alarm <= 1'b0;          // synchronous clear");
  const hasLiteral = tokens.some((t) => t.type === 'literal' && t.text === "1'b0");
  const hasComment = tokens.some((t) => t.type === 'comment' && t.text.includes('// synchronous clear'));
  assert.equal(hasLiteral, true);
  assert.equal(hasComment, true);

  const lines = formatDisplayCodeLines('module alarm_latch();\nendmodule', 'verilog');
  assert.equal(lines[0], '```verilog');
  assert.equal(lines.length, 3);
});
